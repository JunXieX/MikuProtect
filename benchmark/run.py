#!/usr/bin/env python3
"""Deterministic Paper benchmark runner for MikuProtect, CoreProtect and Prism.

The workload is generated by BenchProbe: a fixed flat platform and a fixed TNT burst. Each
variant gets a fresh server directory, world and database. The script reports server tick
metrics and storage footprint; it is a relative comparison, not an absolute TPS guarantee.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import socket
import statistics
import subprocess
import sys
import time
from pathlib import Path

RESULT_RE = re.compile(r"\[BENCH_RESULT\]\s+(.+)")
DONE_MARKER = "BENCH_DONE"
READY_MARKER = "Done ("


def parse_result(line: str) -> dict[str, float | int | str]:
    payload = line.split("[BENCH_RESULT]", 1)[1].strip()
    values: dict[str, float | int | str] = {}
    for token in payload.split():
        if "=" not in token:
            continue
        key, value = token.split("=", 1)
        try:
            values[key] = int(value)
        except ValueError:
            try:
                values[key] = float(value)
            except ValueError:
                values[key] = value
    return values


def log_text(log: Path) -> str:
    try:
        return log.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        return ""


def read_rss_kb(pid: int) -> int:
    if not sys.platform.startswith("linux"):
        return 0
    try:
        for line in Path(f"/proc/{pid}/status").read_text(encoding="utf-8").splitlines():
            if line.startswith("VmRSS:"):
                return int(line.split()[1])
    except (FileNotFoundError, ProcessLookupError, ValueError, OSError):
        pass
    return 0


def wait_for(log: Path, marker: str, timeout: float, process: subprocess.Popen | None = None,
             rss_state: dict | None = None) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process is not None and rss_state is not None:
            rss_state["max_kb"] = max(rss_state.get("max_kb", 0), read_rss_kb(process.pid))
        if marker in log_text(log):
            return True
        time.sleep(0.25)
    return False


def timed_console_command(log: Path, process: subprocess.Popen, command: str, timeout: float,
                         marker: re.Pattern[str], quiet_seconds: float = 1.0) -> float | None:
    """Measure until console output has been quiet long enough and the expected result marker appeared."""
    if process.stdin is None:
        return None
    before_text = log_text(log)
    before = len(before_text.encode("utf-8", errors="replace"))
    started = time.monotonic()
    process.stdin.write(command + "\n")
    process.stdin.flush()
    last_size = before
    last_change = started
    deadline = started + timeout
    while time.monotonic() < deadline:
        time.sleep(0.25)
        text = log_text(log)
        size = len(text.encode("utf-8", errors="replace"))
        if size != last_size:
            last_size = size
            last_change = time.monotonic()
        if size > before and time.monotonic() - last_change >= quiet_seconds:
            new_text = text[len(before_text):]
            if new_text.strip() and marker.search(new_text):
                return round(time.monotonic() - started, 3)
            return None
    return None


def storage_bytes(server_dir: Path) -> int:
    suffixes = {".db", ".sqlite", ".sqlite3", ".duckdb", ".mv.db", ".h2.db", ".wal"}
    total = 0
    plugin_dir = server_dir / "plugins"
    if not plugin_dir.exists():
        return 0
    for path in plugin_dir.rglob("*"):
        if path.is_file() and any(path.name.endswith(suffix) for suffix in suffixes):
            try:
                total += path.stat().st_size
            except OSError:
                pass
    return total


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def write_server_files(server_dir: Path, paper: Path, port: int, runtime_cache: Path | None) -> None:
    (server_dir / "plugins").mkdir(parents=True, exist_ok=True)
    if runtime_cache is not None:
        # Reuse Paper's downloaded vanilla/libraries between otherwise isolated runs.
        for name in ("cache", "libraries", "versions"):
            source = runtime_cache / name
            if source.is_dir():
                shutil.copytree(source, server_dir / name, dirs_exist_ok=True)
    shutil.copy2(paper, server_dir / "paper.jar")
    (server_dir / "eula.txt").write_text("eula=true\n", encoding="ascii")
    (server_dir / "server.properties").write_text(
        "\n".join(
            [
                "online-mode=false",
                f"server-port={port}",
                "level-type=minecraft:flat",
                "generate-structures=false",
                "spawn-protection=0",
                "max-players=100",
                "view-distance=4",
                "simulation-distance=4",
                "enable-command-block=true",
                "allow-flight=true",
                "difficulty=peaceful",
                "spawn-monsters=false",
                "enable-rcon=false",
                "motd=BenchProbe",
                "max-tick-time=180000",
            ]
        )
        + "\n",
        encoding="ascii",
    )


def install_plugins(server_dir: Path, names: list[str], paths: dict[str, Path]) -> None:
    plugins = server_dir / "plugins"
    for name in names:
        source = paths[name]
        if not source.is_file():
            raise FileNotFoundError(f"missing plugin jar: {source}")
        shutil.copy2(source, plugins / source.name)


def write_miku_config(server_dir: Path) -> None:
    config = server_dir / "plugins" / "MikuProtect" / "config.yml"
    config.parent.mkdir(parents=True, exist_ok=True)
    # Fixed profile keeps the comparison independent of the test server's max-players.
    config.write_text("performance:\n  profile: medium\n", encoding="utf-8")


def run_once(args: argparse.Namespace, variant: str, plugins: list[str], run_number: int) -> dict:
    server_dir = args.out / "servers" / f"{variant}-{run_number}"
    shutil.rmtree(server_dir, ignore_errors=True)
    write_server_files(server_dir, args.paper, args.port or free_port(), args.runtime_cache)
    install_plugins(server_dir, plugins, {
        "probe": args.probe,
        "miku": args.miku,
        "coreprotect": args.coreprotect,
        "prism": args.prism,
        "nbtapi": args.nbtapi,
    })
    if "miku" in plugins:
        write_miku_config(server_dir)

    log = server_dir / "benchmark.log"
    command = [
        args.java,
        "-Xms1G",
        "-Xmx2G",
        "-XX:+UseG1GC",
        "-jar",
        str((server_dir / "paper.jar").resolve()),
        "--nogui",
    ]
    started = time.monotonic()
    rss_state = {"max_kb": 0}
    with log.open("w", encoding="utf-8", errors="replace") as output:
        process = subprocess.Popen(
            command,
            cwd=server_dir,
            stdin=subprocess.PIPE,
            stdout=output,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        result: dict = {"variant": variant, "run": run_number, "status": "failed"}
        try:
            if not wait_for(log, READY_MARKER, args.startup_timeout, process, rss_state):
                result["error"] = "server did not become ready"
                result["startup_seconds"] = round(time.monotonic() - started, 3)
                result["max_rss_mb"] = round(rss_state["max_kb"] / 1024, 2)
                result["log_tail"] = "\n".join(log_text(log).splitlines()[-40:])
                return result
            result["startup_seconds"] = round(time.monotonic() - started, 3)
            if process.stdin is None:
                result["error"] = "server stdin unavailable"
                return result
            process.stdin.write(f"benchprobe {args.tnt} {args.ticks}\n")
            process.stdin.flush()
            done = wait_for(log, DONE_MARKER, args.run_timeout, process, rss_state)
            text = log_text(log)
            result_lines = [line for line in text.splitlines() if "[BENCH_RESULT]" in line]
            if not result_lines:
                result["error"] = "probe did not produce a result"
                result["log_tail"] = "\n".join(text.splitlines()[-40:])
                return result
            result.update(parse_result(result_lines[-1]))
            result["status"] = "ok" if done else "result_without_done"
            result["storage_bytes"] = storage_bytes(server_dir)
            if variant != "baseline":
                query_command = {
                    "mikuprotect": "mp lookup t:5m",
                    "coreprotect": "co lookup t:5m",
                    "prism": "prism lookup",
                }.get(variant)
                if query_command:
                    query_marker = {
                        "mikuprotect": re.compile("查询结果"),
                        "coreprotect": re.compile("CoreProtect - (?!Please specify)"),
                        "prism": re.compile("prism|Prism"),
                    }[variant]
                    result["query_seconds"] = timed_console_command(
                            log, process, query_command, 20.0, query_marker)
                if variant != "baseline":
                    rollback_command = {
                        "mikuprotect": "mp rollback t:5m",
                        "coreprotect": "co rollback t:5m",
                        "prism": "prism rollback",
                    }.get(variant)
                    if rollback_command:
                        rollback_marker = {
                            "mikuprotect": re.compile("回滚完成"),
                            "coreprotect": re.compile("Rollback|rollback complete"),
                            "prism": re.compile("Rollback|rollback"),
                        }[variant]
                        result["rollback_seconds"] = timed_console_command(
                                log, process, rollback_command, 60.0, rollback_marker)
            result["max_rss_mb"] = round(rss_state["max_kb"] / 1024, 2)
            result["duration_seconds"] = round(time.monotonic() - started, 3)
            errors = [
                line for line in text.splitlines()
                if any(marker in line for marker in ("SEVERE", "ERROR", "Exception", "Could not load"))
            ]
            result["errors"] = errors[-10:]
            return result
        finally:
            if process.poll() is None and process.stdin is not None:
                try:
                    process.stdin.write("stop\n")
                    process.stdin.flush()
                except (BrokenPipeError, OSError):
                    pass
                try:
                    process.wait(timeout=30)
                except subprocess.TimeoutExpired:
                    process.terminate()
                    try:
                        process.wait(timeout=10)
                    except subprocess.TimeoutExpired:
                        process.kill()
                        process.wait(timeout=10)


def query_text(runs: list[dict]) -> str:
    value = median_value(runs, "query_seconds")
    return f"{value:.3f}" if value else "-"


def rollback_text(runs: list[dict]) -> str:
    value = median_value(runs, "rollback_seconds")
    return f"{value:.3f}" if value else "-"


def median_value(runs: list[dict], key: str) -> float:
    values = [
        float(run[key])
        for run in runs
        if run.get("status") in ("ok", "result_without_done")
        and run.get(key) is not None
    ]
    return float(statistics.median(values)) if values else 0.0


def markdown_report(variants: list[dict], raw: dict) -> str:
    baseline_avg = 0.0
    for variant in variants:
        if variant["name"] == "baseline":
            baseline_avg = median_value(variant["runs"], "interval_avg_ms")
    lines = [
        "# MikuProtect performance comparison",
        "",
        "Same Paper/JVM, flat world, no network players; fixed TNT burst + 200 hoppers + 200 zombies. Values are medians of the runs.",
        "",
        "| Variant | Status | Avg tick interval ms | P95 ms | Max ms | Server avg tick ms | TPS avg | Startup s | Max RSS MiB | Query s | Rollback s | Storage MiB | Δ vs baseline |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for variant in variants:
        runs = variant["runs"]
        ok = any(run.get("status") in ("ok", "result_without_done") for run in runs)
        avg = median_value(runs, "interval_avg_ms")
        delta = f"{avg - baseline_avg:+.3f} ms" if baseline_avg and ok else "-"
        storage = median_value(runs, "storage_bytes") / (1024 * 1024)
        lines.append(
            f"| {variant['name']} | {'ok' if ok else 'failed'} | {avg:.3f} | "
            f"{median_value(runs, 'interval_p95_ms'):.3f} | "
            f"{median_value(runs, 'interval_max_ms'):.3f} | "
            f"{median_value(runs, 'server_tick_avg_ms'):.3f} | "
            f"{median_value(runs, 'tps_avg'):.3f} | "
            f"{median_value(runs, 'startup_seconds'):.3f} | "
            f"{median_value(runs, 'max_rss_mb'):.1f} | "
            f"{query_text(runs)} | {rollback_text(runs)} | {storage:.2f} | {delta} |"
        )
    lines.extend([
        "",
        f"- TNT: {raw['config']['tnt']}, measured ticks: {raw['config']['ticks']}, runs: {raw['config']['runs']}",
        "- CoreProtect 24.2-dev comes from the Midnight-2004 26.3 auto-build release; it is a dev build and can change.",
        "- Storage engines differ by plugin (DuckDB, SQLite/H2/MySQL-capable defaults); storage size is informational.",
        "- Query/rollback seconds are wall-clock console-output quiet times; plugin-specific output/confirmation semantics differ.",
    ])
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", type=Path, required=True)
    parser.add_argument("--probe", type=Path, required=True)
    parser.add_argument("--miku", type=Path, required=True)
    parser.add_argument("--coreprotect", type=Path, required=True)
    parser.add_argument("--prism", type=Path, required=True)
    parser.add_argument("--nbtapi", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("benchmark-results"))
    parser.add_argument("--runs", type=int, default=2)
    parser.add_argument("--tnt", type=int, default=500)
    parser.add_argument("--ticks", type=int, default=200)
    parser.add_argument("--java", default="java")
    parser.add_argument("--port", type=int, default=0, help="server port; 0 picks a free port")
    parser.add_argument("--runtime-cache", type=Path,
                        help="optional Paper directory containing cache/libraries/versions")
    parser.add_argument("--variants", default="baseline,mikuprotect,coreprotect,prism",
                        help="comma-separated variant names")
    parser.add_argument("--startup-timeout", type=float, default=240.0)
    parser.add_argument("--run-timeout", type=float, default=120.0)
    args = parser.parse_args()
    if args.runs < 1 or args.tnt < 1 or args.ticks < 20:
        parser.error("runs/tnt/ticks must be positive")
    args.out.mkdir(parents=True, exist_ok=True)

    all_variants = {
        "baseline": ["probe"],
        "mikuprotect": ["probe", "miku"],
        "coreprotect": ["probe", "coreprotect"],
        "prism": ["probe", "prism", "nbtapi"],
    }
    selected = [name.strip() for name in args.variants.split(",") if name.strip()]
    unknown = [name for name in selected if name not in all_variants]
    if unknown:
        parser.error("unknown variants: " + ", ".join(unknown))
    results: list[dict] = []
    for name in selected:
        plugins = all_variants[name]
        runs = []
        for run_number in range(1, args.runs + 1):
            print(f"running {name} {run_number}/{args.runs}", flush=True)
            runs.append(run_once(args, name, plugins, run_number))
        results.append({"name": name, "runs": runs})

    raw = {
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "config": {"runs": args.runs, "tnt": args.tnt, "ticks": args.ticks},
        "variants": results,
    }
    (args.out / "results.json").write_text(json.dumps(raw, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (args.out / "summary.md").write_text(markdown_report(results, raw), encoding="utf-8")
    print((args.out / "summary.md").read_text(encoding="utf-8"))
    return 0 if any(run.get("status") in ("ok", "result_without_done") for v in results for run in v["runs"]) else 1


if __name__ == "__main__":
    sys.exit(main())
